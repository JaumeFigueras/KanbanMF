#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Sphinx configuration for the KanbanMF documentation.

Builds the narrative documentation (the Markdown files at the repository
root, pulled in via MyST) plus a complete API reference generated from the
backend source with ``autodoc``/``autosummary``.

Build locally with::

    source .venv/bin/activate
    pip3 install -r backend/requirements.txt
    cd docs && make html

For the full list of built-in configuration values, see
https://www.sphinx-doc.org/en/master/usage/configuration.html
"""

import os
import sys
from datetime import date
from pathlib import Path

# -- Path setup --------------------------------------------------------------
# conf.py -> docs/source/ -> docs/ -> <repo root>
_REPO_ROOT = Path(__file__).parent.parent.parent
_BACKEND = _REPO_ROOT / "backend"

# The backend is imported as the top-level ``src`` namespace package
# (``from src.model.board import Board``), so ``backend/`` — not
# ``backend/src/`` — is what has to be on sys.path.
sys.path.insert(0, str(_BACKEND))

# autodoc imports every module it documents, and importing anything under
# ``src`` instantiates ``src.core.config.Settings`` (and fastapi-mail's
# ConnectionConfig) at module level. Those need a handful of settings that
# have no default, and a docs build must not depend on a real backend/.env.
# Environment variables take precedence over the .env file in
# pydantic-settings, so these placeholders keep the build hermetic and free
# of real credentials. Nothing here ever opens a connection.
os.environ.setdefault(
    "DATABASE_URL", "postgresql+psycopg://docs:docs@localhost:5432/docs"
)
os.environ.setdefault("SECRET_KEY", "documentation-build-only-not-a-real-secret-0123456789")
os.environ.setdefault("SMTP_HOST", "localhost")
os.environ.setdefault("SMTP_PORT", "25")
os.environ.setdefault("SMTP_FROM_EMAIL", "docs@example.com")
os.environ.setdefault("SMTP_FROM_NAME", "KanbanMF docs")

# -- Project information -----------------------------------------------------
# https://www.sphinx-doc.org/en/master/usage/configuration.html#project-information

project = "Kanban MF"
copyright = f"{date.today().year}, Jaume Figueras"
author = "Jaume Figueras"
release = "0.1"
version = "0.1"

# -- General configuration ---------------------------------------------------
# https://www.sphinx-doc.org/en/master/usage/configuration.html#general-configuration

extensions = [
    "sphinx.ext.autodoc",       # pull docstrings out of the backend source
    "sphinx.ext.autosummary",   # generate one page per module, recursively
    "sphinx.ext.napoleon",      # Google/NumPy style docstrings
    "sphinx.ext.viewcode",      # "[source]" links next to every object
    "sphinx.ext.intersphinx",   # cross-link to Python/SQLAlchemy/Pydantic docs
    "sphinx.ext.todo",          # .. todo:: directives, rendered (see below)
    "sphinx.ext.coverage",      # `make coverage` reports undocumented objects
    "sphinx.ext.graphviz",      # the architecture diagrams (needs `dot`)
    "myst_parser",              # so the root README.md & friends can be included
]

templates_path = ["_templates"]
exclude_patterns = []

# Warn about broken cross-references; combine with `make html SPHINXOPTS=-W`
# in CI to make them fatal.
nitpicky = False

# MyST is configured so the root Markdown files (README.md, SETUP.md,
# PENDING.md) can be {include}d rather than duplicated. They link to sibling
# repo files (LICENSE, deploy/apache-kanbanmf.conf) that are not documentation
# pages: those links are correct on GitHub, where the files are read from, but
# MyST can't resolve them to a doc. Don't warn about it. Make them absolute
# https://github.com/... URLs in the source files if you want them to work from
# the rendered HTML too.
#
# setup/production.rst includes SETUP.md from its fourth heading level down,
# since its top headings ("Old-fashioned deployment", "Debian") are
# GitHub-only framing; MyST warns that an included document doesn't start at
# H1, which is intended here.
suppress_warnings = ["myst.xref_missing", "myst.header"]

# -- Autodoc / autosummary ---------------------------------------------------

autosummary_generate = True
autosummary_imported_members = False

autodoc_default_options = {
    "members": True,
    "undoc-members": True,
    "show-inheritance": True,
    "member-order": "bysource",
    # src/model/__init__.py re-exports every model through __all__, which
    # autodoc would otherwise honour — documenting e.g. User both as
    # src.model.User and src.model.user.User and making every cross-reference
    # to it ambiguous. Ignoring __all__ documents each object only where it is
    # actually defined.
    "ignore-module-all": True,
}
# Keep signatures readable: don't expand type aliases or evaluate defaults.
autodoc_typehints = "signature"
autodoc_preserve_defaults = True
# SQLAlchemy models get an autogenerated __init__ signature that says nothing.
autoclass_content = "class"
autodoc_class_signature = "mixed"
# Anything that can't be imported at build time (none today) goes here rather
# than breaking the build.
autodoc_mock_imports = []

# -- Napoleon ----------------------------------------------------------------

napoleon_google_docstring = True
napoleon_numpy_docstring = True
napoleon_include_init_with_doc = True
napoleon_include_private_with_doc = False
napoleon_use_admonition_for_examples = True
napoleon_use_admonition_for_notes = True
napoleon_use_rtype = True

# -- Intersphinx -------------------------------------------------------------
# Fetched over the network; a short timeout means an offline build degrades to
# a warning instead of hanging.

intersphinx_mapping = {
    "python": ("https://docs.python.org/3", None),
    "sqlalchemy": ("https://docs.sqlalchemy.org/en/20/", None),
    "pydantic": ("https://docs.pydantic.dev/latest/", None),
    "alembic": ("https://alembic.sqlalchemy.org/en/latest/", None),
}
intersphinx_timeout = 5

# -- MyST (Markdown) ---------------------------------------------------------

myst_enable_extensions = [
    "colon_fence",
    "deflist",
    "fieldlist",
    "linkify",
    "substitution",
    "tasklist",
]
myst_heading_anchors = 3

source_suffix = {
    ".rst": "restructuredtext",
    ".md": "markdown",
}

# -- Graphviz ----------------------------------------------------------------
# SVG scales with the page and keeps its text selectable. Needs the `dot`
# binary: `apt install graphviz` locally; .readthedocs.yaml installs it there.

graphviz_output_format = "svg"
graphviz_dot_args = [
    "-Gfontname=Lato", "-Nfontname=Lato", "-Efontname=Lato",
    "-Gbgcolor=transparent", "-Nfontsize=11", "-Efontsize=10",
]

# -- Todo --------------------------------------------------------------------

todo_include_todos = True

# -- Options for HTML output -------------------------------------------------
# https://www.sphinx-doc.org/en/master/usage/configuration.html#options-for-html-output

html_theme = "sphinx_rtd_theme"
html_static_path = ["_static"]
html_css_files = ["custom.css"]
html_title = f"{project} {release}"

html_theme_options = {
    "logo_only": False,
    "prev_next_buttons_location": "bottom",
    "style_external_links": True,
    "collapse_navigation": False,
    "sticky_navigation": True,
    "navigation_depth": 4,
    "includehidden": True,
    "titles_only": False,
}

html_show_sourcelink = True

# -- Options for LaTeX / PDF output ------------------------------------------
# Read the Docs builds a PDF of each language (.readthedocs.yaml, formats) with
# pdflatex, Sphinx's default engine for English and Catalan. Its utf8 input
# handles accents, curly quotes, dashes and guillemets, but not U+2630 (☰),
# which the manual uses for the menu buttons: map it to a three-bar ≡ rather
# than let the PDF build stop on it. The \ifdefined guard keeps a xelatex or
# lualatex build, which has no \DeclareUnicodeCharacter, working.

latex_elements = {
    "papersize": "a4paper",
    "preamble": r"""
\ifdefined\DeclareUnicodeCharacter
  \DeclareUnicodeCharacter{2630}{\ensuremath{\equiv}}
\fi
""",
}

# -- Internationalisation ----------------------------------------------------
# English is the source language. Translations live as gettext catalogues in
# docs/locale/<lang>/LC_MESSAGES/, one .po file per document
# (gettext_compact = False), and a build in another language is just
# `-D language=<lang>`. Anything not translated yet falls back to English.
#
# Only the user manual and the landing page are translated; the developer
# pages and the generated API reference stay in English. That scope is decided
# by which catalogues `make docs-po` (root Makefile) creates, not here.
#
# Images follow the same rule: `.. figure:: img/board.png` resolves to
# img/board.ca.png in a Catalan build when that file exists, and to
# img/board.png otherwise.

language = "en"
locale_dirs = ["../locale/"]
gettext_compact = False
# No "#: file:line" comments in the catalogues — they change on every edit
# above a paragraph and would bury the real changes in .po diffs.
gettext_location = False
figure_language_filename = "{path}{basename}.{language}{ext}"

# The languages the docs are built in, in switcher order. The switcher itself
# (_templates/layout.html) is only drawn when the build passes
# `-A docs_switcher=1`, which `make docs` does: it relies on the languages
# sitting side by side in build/site/<lang>/. A plain `make html` (one
# language) and Read the Docs (which draws its own language menu) don't.
html_context = {"docs_languages": {"en": "English", "ca": "Català"}}
